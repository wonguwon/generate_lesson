def pct(part, total):
    return float((Decimal(part) * 100 / Decimal(total)).quantize(Decimal("0.1"), ROUND_HALF_UP))


def change(old, new):
    return float(((Decimal(new) - Decimal(old)) * 100 / Decimal(old)).quantize(Decimal("0.1"), ROUND_HALF_UP))


def summarize(rows):
    """지점·상품·일자별 (건수, 수량, 매출액)."""
    def group(idx):
        g = OrderedDict()
        for r in rows:
            c = g.setdefault(r[idx], [0, 0, 0])
            c[0] += 1
            c[1] += r[4]
            c[2] += r[5]
        return g
    total = sum(r[5] for r in rows)
    return {
        "count": len(rows),
        "qty": sum(r[4] for r in rows),
        "sales": total,
        "branch": sorted(group(0).items(), key=lambda kv: -kv[1][2]),
        "product": sorted(group(3).items(), key=lambda kv: -kv[1][2]),
        "date": sorted(group(1).items()),
    }


def check_prices(rows):
    bad = [r for r in rows if r[4] * PRICE[r[3]] != r[5]]
    assert not bad, f"수량×단가와 매출이 다른 행: {bad}"
