def read_csv(text):
    return list(csv.reader(io.StringIO(text)))


def norm_date(s):
    m = re.fullmatch(r"(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})", s.strip()) or \
        re.fullmatch(r"(\d{4})년 (\d{1,2})월 (\d{1,2})일", s.strip())
    assert m, f"알 수 없는 날짜 형식: {s}"
    return date(int(m[1]), int(m[2]), int(m[3])).isoformat()


def day_label(iso):
    d = date.fromisoformat(iso)
    return f"{iso}({WEEKDAY[d.weekday()]})"


def daejeon_cleaned():
    """정리 규칙 3가지를 적용한 대전점 (머리글 포함)."""
    rows = read_csv(W1_RAW["대전점"])
    head, body = rows[0], rows[1:]
    out, seen = [], set()
    for r in body:
        if tuple(r) in seen:
            continue
        seen.add(tuple(r))
        out.append([norm_date(r[0]), r[1], r[2], int(r[3]), int(r[4]), r[5] or "미기재"])
    return head, out


def merged_rows():
    """5개 파일을 열 짝대로 그대로 합친 상태 (대구점 천원 단위·부산점 중복 그대로, 47행)."""
    out = []
    for br, text in W1_RAW.items():
        if br == "대전점":
            _, body = daejeon_cleaned()
        else:
            body = read_csv(text)[1:]
        for r in body:
            out.append([br, norm_date(str(r[0])), r[1], r[2], int(r[3]), int(r[4])])
    return out


def final_rows():
    """정답 최종본 (부산점 BS-1009 중복 1행 제거, 대구점 원 단위, 46행)."""
    out, seen = [], set()
    for r in merged_rows():
        r = list(r)
        if r[0] == "대구점":
            r[5] *= 1000
        key = tuple(r)
        if r[0] == "부산점" and key in seen:
            continue
        seen.add(key)
        out.append(r)
    return out


