# ---- 정답 계산 (자료 조건 그대로) ----
TEAM = 10
VAT = 1.1
services = [
    # 이름, 요금 방식(자료 그대로), 10명 월 요금, 계산식, 무료 플랜, 무료 체험
    ("도란보드", "1인당 월 9,900원 (부가세 별도)", round(9900 * TEAM * VAT), "9,900 × 10명 × 1.1(부가세)", "있음 (3명까지)", "14일"),
    ("일감나루", "연간 결제 시 1인당 월 8,000원 / 월간 결제 시 1인당 월 10,000원 (부가세 포함)", 10000 * TEAM, "10,000 × 10명 (월간 결제, 부가세 포함)", "없음", "없음"),
    ("플랜고래", "기본 요금 월 49,000원 (5명 포함), 6번째 사람부터 1명당 월 9,000원 추가 (부가세 포함)", 49000 + 9000 * (TEAM - 5), "49,000 + 9,000 × 5명(6~10번째)", "없음", "30일"),
    ("업무콩", "1인당 월 7,500원 (부가세 별도), 최소 10명부터 계약", round(7500 * TEAM * VAT), "7,500 × 10명 × 1.1(부가세)", "없음", "7일"),
    ("팀솔솔", "월 97,000원 정액, 최대 10명까지 (부가세 포함)", 97000, "97,000 정액 (부가세 포함)", "있음 (2명까지)", "없음"),
]
expected = {"업무콩": 82500, "플랜고래": 94000, "팀솔솔": 97000, "일감나루": 100000, "도란보드": 108900}
assert {s[0]: s[2] for s in services} == expected, "정답 표와 계산이 다릅니다"
ranked5 = sorted(services, key=lambda s: s[2])
ranked3 = sorted([s for s in services if s[0] in ("도란보드", "일감나루", "플랜고래")], key=lambda s: s[2])
assert [s[0] for s in ranked5] == ["업무콩", "플랜고래", "팀솔솔", "일감나루", "도란보드"]
assert [s[0] for s in ranked3] == ["플랜고래", "일감나루", "도란보드"]

HEAD = Font(bold=True, color="FFFFFF")
HEAD_FILL = PatternFill("solid", fgColor="1F4E78")
WRONG_FILL = PatternFill("solid", fgColor="F8CBAD")
WRAP = Alignment(wrap_text=True, vertical="top")


def write_table(ws, header, rows, widths, money_cols=()):
    ws.append(header)
    for c in ws[1]:
        c.font, c.fill, c.alignment = HEAD, HEAD_FILL, WRAP
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = WRAP
            if c.column in money_cols:
                c.number_format = '#,##0"원"'
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[chr(64 + i)].width = w
    ws.freeze_panes = "A2"


# ---- 강사용 정답 파일 ----
wb = Workbook()
ws = wb.active
ws.title = "정답_5곳"
write_table(
    ws,
    ["순위", "서비스", "계산", "10명 팀 월 요금", "무료 플랜", "무료 체험"],
    [(i, s[0], s[3], s[2], s[4], s[5]) for i, s in enumerate(ranked5, start=1)],
    [6, 12, 42, 16, 16, 10],
    money_cols=(4,),
)
ws.append([])
ws.append(["기준: 10명 팀, 월간 결제, 부가세 포함"])

ws = wb.create_sheet("정답_3곳(방향 바꾸기 전)")
write_table(
    ws,
    ["순위", "서비스", "계산", "10명 팀 월 요금", "무료 플랜"],
    [(i, s[0], s[3], s[2], s[4]) for i, s in enumerate(ranked3, start=1)],
    [6, 12, 42, 16, 16],
    money_cols=(4,),
)
ws.append([])
ws.append(["4단계 요청을 실행 전에 바로 승인했을 때(5곳으로 바꾸기 전)의 정답입니다."])

ws = wb.create_sheet("생길 수 있는 실수")
write_table(
    ws,
    ["확인할 곳", "정답", "생길 수 있는 실수"],
    [
        ("행 수", "5개", "방향을 바꾸기 전의 3곳만 남아 있음"),
        ("부가세 별도인 곳 (도란보드·업무콩)", "108,900원 / 82,500원", "부가세를 빼고 99,000원 / 75,000원으로 적음"),
        ("일감나루 결제 방식", "100,000원", "연간 결제 가격으로 80,000원이라고 적음"),
        ("플랜고래 계산", "94,000원", "9,000 × 10명 = 90,000원처럼 기본 요금 구조를 놓침"),
        ("무료 체험 열", "팀솔솔·일감나루는 '없음'", "팀솔솔의 무료 플랜을 무료 체험으로 착각"),
        ("순위", "업무콩 → 플랜고래 → 팀솔솔 → 일감나루 → 도란보드", "도란보드 부가세가 빠지면 99,000원으로 4위가 됨"),
    ],
    [34, 40, 50],
)
wb.save(TEACHER / "정답_요금비교표.xlsx")

# ---- 강사용 시연 파일: 도란보드 부가세가 빠진 결과 (수정 요청 시연용) ----
wrong = {s[0]: s[2] for s in services}
wrong["도란보드"] = 9900 * TEAM  # 부가세 누락
wrong_rank = sorted(services, key=lambda s: wrong[s[0]])
assert [s[0] for s in wrong_rank] == ["업무콩", "플랜고래", "팀솔솔", "도란보드", "일감나루"]
wb = Workbook()
ws = wb.active
ws.title = "비교표"
write_table(
    ws,
    ["순위", "서비스명", "요금 방식", "10명 팀 월 요금", "무료 플랜", "무료 체험"],
    [(i, s[0], s[1], wrong[s[0]], s[4], s[5]) for i, s in enumerate(wrong_rank, start=1)],
    [6, 12, 60, 16, 16, 10],
    money_cols=(4,),
)
for row in ws.iter_rows(min_row=2):
    if row[1].value == "도란보드":
        row[3].fill = WRONG_FILL
ws = wb.create_sheet("요약")
ws.column_dimensions["A"].width = 90
for line in [
    "1. 10명 팀 월 요금은 업무콩이 82,500원으로 가장 낮습니다.",
    "2. 플랜고래(94,000원)와 팀솔솔(97,000원)이 뒤를 잇고, 도란보드는 99,000원으로 4위입니다.",
    "3. 일감나루는 100,000원으로 가장 높습니다.",
]:
    ws.append([line])
wb.save(TEACHER / "시연용_오답예시_도란보드부가세누락.xlsx")

# ---- 학습자용 텍스트 (Windows 메모장에서 한글이 깨지지 않게 BOM 포함) ----
(LEARNER / "협업툴_요금안내.txt").write_text(DATA, encoding="utf-8-sig")
(LEARNER / "실습_요청문.txt").write_text(PROMPTS, encoding="utf-8-sig")
print("ok")
