"""2차시 '파일 맡기고 결과 파일 받기' 실습 파일 생성. usage: python make_02.py <chatgpt-web-basics 폴더>"""
import sys
from pathlib import Path

from openpyxl import Workbook

import haru_data as H
import writers as W

ROOT = Path(sys.argv[1]) / "02_파일_맡기고_결과파일_받기"
L, T = ROOT / "학습자용", ROOT / "강사용"

# ---- 교안 정답 표와 대조 ----
for br, text in H.W1_RAW.items():
    body = H.read_csv(text)[1:]
    assert len(body) == {"강남점": 12, "수원점": 8, "대전점": 10, "대구점": 7, "부산점": 11}[br]
raw_dj = H.read_csv(H.W1_RAW["대전점"])[1:]
assert sum(int(r[4]) for r in raw_dj) == 501000
assert sum(1 for r in raw_dj if not r[5]) == 3
dj_head, dj = H.daejeon_cleaned()
assert len(dj) == 9 and sum(r[4] for r in dj) == 476000
assert [r[1] for r in dj if r[5] == "미기재"] == ["DJ-1004", "DJ-1008"]
assert sum(r[4] for r in dj if r[5] != "미기재") == 361000 and len([r for r in dj if r[5] != "미기재"]) == 7

merged = H.merged_rows()
assert len(merged) == 47
assert sum(r[5] for r in merged) == 1873271
assert sum(r[5] * (1000 if r[0] == "대구점" else 1) for r in merged) == 2144000
assert len({(r[0], r[2]) for r in merged}) == 46

orig_sum = {br: sum(int(r[-1] if br != "대전점" else r[4]) for r in
                    (H.read_csv(t)[1:] if br != "대전점" else dj)) for br, t in H.W1_RAW.items()}
assert orig_sum == {"강남점": 411000, "수원점": 508000, "대전점": 476000, "대구점": 271, "부산점": 478000}

final = H.final_rows()
H.check_prices(final)
S = H.summarize(final)
assert S["count"] == 46 and S["sales"] == 2054000
assert [(b, v[0], v[2]) for b, v in S["branch"]] == [
    ("수원점", 8, 508000), ("대전점", 9, 476000), ("강남점", 12, 411000), ("부산점", 10, 388000), ("대구점", 7, 271000)]
assert [r for r in final if r[2] == "DG-1003"][0][5] == 100000
assert sum(1 for r in final if r[2] == "BS-1009") == 1
assert all(r[1].startswith("2026-10-1") and "2026-10-12" <= r[1] <= "2026-10-16" for r in final)

# ---- 학습자용 ----
NAMES = {br: f"{br}_1주차.csv" for br in H.BRANCHES}
for br, text in H.W1_RAW.items():
    W.write_text(L / NAMES[br], text)

PROMPTS = """파일 맡기고 결과 파일 받기 - 실습 요청문 모음
교안의 순서대로 적었습니다. 필요한 블록만 복사해 ChatGPT(Work) 입력창에 붙여넣습니다.
파일은 요청을 보내기 전에 입력창 왼쪽 + 아이콘이나 끌어다 놓기로 먼저 올립니다.

==================================================
["정리"의 뜻은 내가 정한다] 올릴 파일: 대전점_1주차.csv
==================================================
첨부한 대전점_1주차.csv를 아래 규칙대로 정리해서 새 엑셀 파일로 만들어줘.

정리 규칙
1. 일자: 모두 YYYY-MM-DD 형식으로 통일해. (예: 2026-10-14)
2. 중복: 모든 칸이 완전히 똑같은 행은 하나만 남겨.
3. 빈칸: 담당자 칸이 비어 있으면 '미기재'라고 적어.

- 위 3가지 말고는 아무것도 바꾸지 마.
- 파일 이름은 대전점_1주차_정리.xlsx로 저장해줘.
- 정리 전과 후의 행 수, 매출 합계, 바꾼 내용을 표로 알려줘.

==================================================
[열 이름이 달라도 하나로] 올릴 파일 5개
강남점_1주차.csv, 수원점_1주차.csv, 대전점_1주차_정리.xlsx(앞에서 받은 정리본), 대구점_1주차.csv, 부산점_1주차.csv
==================================================
첨부한 파일 5개를 하나의 엑셀 파일로 합쳐줘.
대상: 강남점_1주차.csv, 수원점_1주차.csv, 대전점_1주차_정리.xlsx, 대구점_1주차.csv, 부산점_1주차.csv

열 맞추기 기준
1. 합친 파일의 열은 이 순서로 만들어: 지점, 판매일, 주문번호, 상품명, 수량, 매출액(원)
2. 파일마다 이름이 다른 열은 아래처럼 같은 열로 봐.
   - 판매일 = 날짜 = 일자 = 거래일 = Date
   - 주문번호 = 주문ID = 주문 번호 = Order No
   - 상품명 = 품목 = 상품 = 제품 = Item
   - 수량 = 판매수량 = 개수 = Qty
   - 매출액(원) = 매출액 = 금액(원) = 매출 = 매출(천원) = Sales
3. '지점' 열을 새로 만들고, 파일 이름 앞부분(강남점, 수원점, 대전점, 대구점, 부산점)을 적어.
4. 위 목록에 없는 열(담당자)은 빼.
5. 판매일은 YYYY-MM-DD 형식으로 통일해.

먼저 계획을 보여 주고, 합친 파일은 하루담리빙_1주차_병합.xlsx로 저장해줘.

==================================================
["일치"도 숫자로 다시 본다] 병합을 맡긴 같은 대화에
==================================================
원본 5개 파일별 건수·합계와 병합 결과를 대조표로 보여줘.
- 행: 강남점, 수원점, 대전점, 대구점, 부산점, 전체
- 열: 원본 건수, 원본 매출 합계(원본 파일에 적힌 숫자 그대로), 병합 파일 건수, 병합 파일 매출액(원) 합계, 일치 여부
- 대전점 원본은 대전점_1주차_정리.xlsx를 기준으로 해.
- 표 아래에 지점별로 주문번호가 몇 개인지(같은 번호는 하나로 셈)도 알려줘.

==================================================
[짚어서 한 번 더] 같은 대화에
==================================================
병합 파일에서 두 군데를 고쳐줘.

1. 부산점 주문번호 BS-1009가 2번 들어가 있어. 두 행은 모든 칸이 같으니 하나만 남겨.
   고친 뒤 부산점은 10건, 매출액 합계 388,000원이어야 해.
   BS-1009가 이미 한 행뿐이면 1번은 하지 말고 그렇다고 알려줘.
2. 대구점 매출액이 천원 단위로 들어가 있어. 원본 열 이름이 '매출(천원)'이니 대구점 7행의 매출액에 1,000을 곱해서 원 단위로 바꿔.
   고친 뒤 대구점 매출액 합계는 271,000원이어야 해.
   대구점 매출액이 이미 원 단위로 바뀌어 있으면 2번은 하지 말고 그렇다고 알려줘.

나머지는 그대로 둬.
고친 파일은 하루담리빙_1주차_최종.xlsx로 저장하고, 고치기 전과 후의 지점별 건수·합계를 대조표로 다시 보여줘.

--------------------------------------------------
[짚어서 한 번 더] 처음부터 정답과 맞았을 때의 연습
--------------------------------------------------
'지점별 요약' 시트를 새로 추가해서 지점, 건수, 매출액(원) 합계를 적어줘. 기존 시트는 그대로 둬.
"""
W.write_text(L / "실습_요청문.txt", PROMPTS)

# ---- 강사용: 단계별 정답 파일 ----
T.mkdir(parents=True, exist_ok=True)
wb = Workbook()
W.add_sheet(wb, "데이터", dj_head, dj, widths=[12, 12, 10, 8, 10, 10], money_cols=(5,), first=True)
wb.save(T / "정답_대전점_1주차_정리.xlsx")
W.save_data_xlsx(T / "정답_하루담리빙_1주차_병합(고치기 전).xlsx", H.HEADER, merged)
W.save_data_xlsx(T / "정답_하루담리빙_1주차_최종.xlsx", H.HEADER, final)

# ---- 강사용: 대조표 ----
cnt_order = {br: len({r[2] for r in merged if r[0] == br}) for br in H.BRANCHES}
cnt_rows = {br: sum(1 for r in merged if r[0] == br) for br in H.BRANCHES}
fin = {b: v for b, v in S["branch"]}
wb = Workbook()
W.add_sheet(wb, "정리 전후(대전점)", ["확인할 것", "정리 전 (원본)", "정리 후 (정답)"], [
    ("행 수 (머리글 제외)", 10, 9),
    ("매출 합계", 501000, 476000),
    ("일자 형식", "4가지가 섞임 (2026-10-12 / 2026/10/13 / 2026.10.13 / 2026년 10월 14일)", "모두 YYYY-MM-DD"),
    ("지운 행", "-", "DJ-1004 중복 1행"),
    ("'미기재'", "담당자 빈칸 3칸 (중복 행 포함)", "2칸 (DJ-1004, DJ-1008)"),
    ("담당자가 빈 행까지 지웠을 때 (실수)", "-", "7행, 361,000원"),
], widths=[34, 46, 30], money_cols=(2, 3), first=True)
rows = []
for br in H.BRANCHES:
    rows.append((br + (" (정리본)" if br == "대전점" else ""), cnt_rows[br], orig_sum[br], cnt_order[br], fin[br][0], fin[br][2]))
rows.append(("전체", sum(cnt_rows.values()), "-", sum(cnt_order.values()), S["count"], S["sales"]))
W.add_sheet(wb, "대조표 정답", ["지점", "원본 건수", "원본 매출 합계 (파일에 적힌 그대로)", "주문번호 개수", "정답 건수", "정답 매출액(원)"],
            rows, widths=[16, 10, 22, 12, 10, 16], money_cols=(3, 6),
            notes=["대구점 원본 합계 271은 천원 단위입니다. 부산점은 11행인데 주문번호는 10개입니다(BS-1009 중복)."])
W.add_sheet(wb, "병합 상태별 합계", ["병합 파일의 상태", "병합 파일 건수", "병합 파일 매출액 합계"], [
    ("대구점 숫자를 그대로 옮긴 경우", 47, 1873271),
    ("대구점을 원 단위로 바꾼 경우", 47, 2144000),
    ("정답 (중복 1건 빼고, 모두 원 단위)", 46, 2054000),
], widths=[36, 14, 20], money_cols=(3,))
W.add_sheet(wb, "고친 뒤 정답", ["지점", "고치기 전 건수", "고치기 전 매출액(원)", "고친 뒤 건수 (정답)", "고친 뒤 매출액(원) (정답)"],
            [(br, cnt_rows[br], {"대구점": "271 또는 271,000"}.get(br, orig_sum[br]), fin[br][0], fin[br][2]) for br in H.BRANCHES]
            + [("전체", 47, "1,873,271 또는 2,144,000", 46, 2054000)],
            widths=[10, 14, 24, 18, 22], money_cols=(3, 5),
            notes=["고친 뒤 지점 순위: 수원점 → 대전점 → 강남점 → 부산점 → 대구점",
                   "부산점 직접 계산: =SUM(E2:E12) → 478,000 (중복 포함), BS-1009는 두 행"])
W.add_sheet(wb, "일부러 넣은 문제", ["지점", "넣어 둔 문제", "고치는 섹션"], [
    ("대전점", "일자 형식 4가지가 섞임, DJ-1004 완전 중복 1행, 담당자 빈칸 3칸(중복 행 포함)", "\"정리\"의 뜻은 내가 정한다"),
    ("수원점", "날짜가 2026.10.12 형식", "열 이름이 달라도 하나로"),
    ("부산점", "영어 열 이름", "열 이름이 달라도 하나로"),
    ("부산점", "BS-1009 완전 중복 1행(파일 맨 아래)", "짚어서 한 번 더"),
    ("대구점", "매출이 천원 단위(열 이름 '매출(천원)')", "짚어서 한 번 더"),
], widths=[10, 70, 30])
wb.save(T / "정답_대조표.xlsx")

