assert [str(M.man(v)) for _, v in P] == ["69.7", "43.9", "43.4"] and str(M.man(1570000)) == "157.0"
assert M.man(439000) - M.man(434000) == M.man(5000)  # 2·3위 0.5만원 차이
# 기간 밖 행이 섞일 때: 9/30 → 경영지원팀 2위, 10/27 → 1위
