assert sorted(mix930, key=lambda k: -mix930[k]).index("경영지원팀") == 1
mix1027 = dict(P); mix1027["경영지원팀"] += 398000
assert sorted(mix1027, key=lambda k: -mix1027[k]).index("경영지원팀") == 0

