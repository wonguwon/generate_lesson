from datetime import date
from decimal import ROUND_HALF_UP, Decimal

YEAR = 2026
WEEKDAY = "월화수목금토일"


def wd(d):
    return WEEKDAY[d.weekday()]


def label(d):
    """2026-11-06(금)"""
    return f"{d.isoformat()}({wd(d)})"


def D(m, d):
    return date(YEAR, m, d)


def r1(x):
    """소수 첫째 자리 반올림 (사사오입)."""
    return Decimal(x).quantize(Decimal("0.1"), ROUND_HALF_UP)


def pct(num, den):
    return r1(Decimal(num) * 100 / Decimal(den))


def change(old, new):
    return r1((Decimal(new) - Decimal(old)) * 100 / Decimal(old))


def sgn(x):
    """+8.0% / −4.0% (교안의 빼기 기호 U+2212)"""
    return f"+{x}%" if x >= 0 else f"−{abs(x)}%"


def man(won):
    """원 → 만원 (Decimal, 소수 첫째 자리)."""
    return r1(Decimal(won) / 10000)


