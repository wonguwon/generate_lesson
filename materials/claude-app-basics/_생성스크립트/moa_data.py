def decisions(text):
    """'- 결정:' 줄과 그 안건 이름."""
    out, agenda = [], None
    for line in text.split("\n"):
        m = re.match(r"^\d+\. (.+)$", line)
        if m:
            agenda = m.group(1)
        if line.startswith("- 결정:"):
            out.append((line[len("- 결정:"):].strip(), agenda))
    return out


