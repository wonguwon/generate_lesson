def raw_order_rows(m):
    """CSV에 들어갈 행(문자열 리스트, 열 순서는 ORDER_COLS)."""
    import datetime as dt
    fmt = DATE_FMT.get(m, "%Y-%m-%d")
    staff = {c[1]: c[4] for c in CLIENTS}

    def row(no, d, c, p, q, u, s, note):
        d = dt.date.fromisoformat(d).strftime(fmt)
        return [no, d, c, p, "" if q is None else str(q), str(u), "" if q is None else str(q * u), s, note]

    out = []
    for r in ORDERS[m]:
        out.append(row(*r))
        if r[0] in MESS[m]["exact"]:
            out.append(row(*r))
        if r[0] in MESS[m]["reentry"]:
            out.append(row(*r[:7], "재입력"))
    for no, d, c, p in MESS[m]["blank"]:
        out.append(row(no, d, c, p, None, PRICE[p], staff[c], ""))
    return out


def order_answers(m):
    rows = ORDERS[m]
    total = sum(r[4] * r[5] for r in rows)
    by_client, by_product = {}, {}
    for r in rows:
        by_client[r[2]] = by_client.get(r[2], 0) + r[4] * r[5]
        by_product[r[3]] = by_product.get(r[3], 0) + r[4] * r[5]
    top_c = sorted(by_client.items(), key=lambda x: -x[1])
    top_p = sorted(by_product.items(), key=lambda x: -x[1])
    mess = MESS[m]
    return {"raw": len(raw_order_rows(m)), "clean": len(rows), "total": total,
            "dup": len(mess["exact"]) + len(mess["reentry"]), "exact": len(mess["exact"]),
            "reentry": len(mess["reentry"]), "blank": len(mess["blank"]),
            "blank_no": [b[0] for b in mess["blank"]],
            "top_clients": top_c, "top_products": top_p,
            "staff": {c[1]: c[4] for c in CLIENTS}}
