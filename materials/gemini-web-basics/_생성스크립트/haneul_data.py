def is_oct(d):
    return D(2026, 10, 1) <= d <= D(2026, 10, 31)


def dept_rows(rows, unit, in_period=is_oct, dedupe=True):
    """{분류: 원} 합계."""
    seen, out = set(), {}
    for d, no, cat, _, amt in rows:
        if not in_period(d) or (dedupe and no in seen):
            continue
        seen.add(no)
        out[cat] = out.get(cat, 0) + amt * unit
    return out


