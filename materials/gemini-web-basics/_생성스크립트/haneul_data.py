import re
from datetime import date as D
from decimal import Decimal, ROUND_HALF_UP

WEEK = "월화수목금토일"


def wd(d):
    return WEEK[d.weekday()]


def check_weekdays(text, label):
    """'11월 12일(목)' 표기의 요일이 2026년 달력과 맞는지 확인."""
    n = 0
    for m, day, w in re.findall(r"(\d+)월 (\d+)일\((.)\)", text):
        assert wd(D(2026, int(m), int(day))) == w, (label, m, day, w)
        n += 1
    return n


def pct(a, b):
    """소수점 첫째 자리 반올림(사사오입)."""
    return str((Decimal(a) * 100 / Decimal(b)).quantize(Decimal("0.1"), ROUND_HALF_UP))


def man(v):
    """원 → 만원, 소수점 첫째 자리."""
    return str((Decimal(v) / 10000).quantize(Decimal("0.1"), ROUND_HALF_UP))


