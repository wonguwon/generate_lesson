def blocks(title, intro, items):
    """실습_요청문.txt 본문. items = [(머리말, 요청문), ...]"""
    bar = "=" * 50
    out = [title, *intro, ""]
    for head, body in items:
        out += [bar, head, bar, body.strip("\n"), ""]
    return "\n".join(out)
