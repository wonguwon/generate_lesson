# ---------------- 교안 정답과 대조 ----------------
A = M.sep_answer()
assert [(r[0], r[1], M.man(r[2]), r[3]) for r in A] == [
    ("마케팅팀", "광고비", "82.0", "M-0901, M-0904"),
    ("영업팀", "접대비", "33.0", "S-0902, S-0904"),
    ("마케팅팀", "행사비", "31.0", "M-0902, M-0905"),
    ("영업팀", "출장비", "21.0", "S-0901, S-0906"),
    ("마케팅팀", "소모품", "9.0", "M-0903, M-0906"),
    ("영업팀", "소모품", "6.0", "S-0903, S-0905"),
]
total = sum(r[2] for r in A)
assert M.man(total) == "182.0"
assert M.man(sum(r[2] for r in A if r[0] == "영업팀")) == "60.0"
assert M.man(sum(r[2] for r in A if r[0] == "마케팅팀")) == "122.0"
# 3교시 예산 문서의 9월 지출과 같아야 함
assert {(d, c): s for d, c, _, s in M.BUDGET} == {(r[0], r[1]): r[2] // 10000 for r in A}

