     ("[실습 4] ④ notice-tone 지침 1번 바꾸기 - 스킬 페이지(매번 적기 번거로울 때)", "1. 다른 스킬이 제목을 정하면 그 제목을 따름. 없으면 맨 위에 [공지]로 시작하는 제목 한 줄"),
